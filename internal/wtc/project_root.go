// RootSelectionFile is the generated tool configuration at a project root. It
// selects the CLI release that the project's harness pins, so commands such
// as `taba new` work from the root without a global default. It is a
// derivative of the harness pin, never an input of its own: the pin is read
// from the harness's shared owner at the harness's registry default ref, the
// same commit a new collection starts from. Collections keep their own
// mise.toml, which wins inside them.
const RootSelectionFile = ".mise/config.toml"

// rootSelectionMarker identifies a file this CLI generated and may rewrite.
// Anything else at RootSelectionFile belongs to the user.
const rootSelectionMarker = "project-root-selection/v1"

const rootSelectionHeader = `# Generated by taba from the project harness pin. Do not edit:
# regenerate with ` + "`taba env root`" + `. Collections keep their own mise.toml.
`

// Root selection states.
const (
	RootSelectionCurrent  = "current"
	RootSelectionStale    = "stale"
	RootSelectionMissing  = "missing"
	RootSelectionConflict = "conflict"
)

var rootRefPattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._/-]*$`)

// RootSelectionSource names the authoritative project source of the root
// selection and what it resolved to.
type RootSelectionSource struct {
	Harness string `json:"harness"`
	Owner   string `json:"owner,omitempty"`
	Ref     string `json:"ref"`
	Commit  string `json:"commit,omitempty"`
	Pin     string `json:"pin,omitempty"`
	Version string `json:"version,omitempty"`
}

// CollectionSelection is the CLI selection a collection applies inside it.
type CollectionSelection struct {
	Collection    string `json:"collection"`
	Version       string `json:"version,omitempty"`
	HarnessCommit string `json:"harness_commit,omitempty"`
	// Differs is set when the collection selects another release than the
	// project source, for example because its harness is on another revision.
	Differs bool `json:"differs"`
}

// RootSelectionReport distinguishes the project source, the generated root
// selection and, when run in a collection, that collection's own selection.
type RootSelectionReport struct {
	Root     string               `json:"root"`
	File     string               `json:"file"`
	State    string               `json:"state"`
	Source   *RootSelectionSource `json:"source,omitempty"`
	Recorded *RootSelectionSource `json:"recorded,omitempty"`
	// SourceError explains why the project source could not be resolved.
	SourceError string `json:"source_error,omitempty"`
	// Overrides lists other root configuration that also selects the CLI and
	// takes precedence over the generated file. They are reported, not changed.
	Overrides  []string             `json:"overrides,omitempty"`
	Collection *CollectionSelection `json:"collection,omitempty"`
	Changed    bool                 `json:"changed"`
	DryRun     bool                 `json:"dry_run"`
	// MiseMissing is set when no mise is on PATH: the file still records the
	// source, but the CLI must be put on PATH another way.
	MiseMissing bool   `json:"mise_missing,omitempty"`
	Content     string `json:"-"`
}

// RootSyncOptions selects how a root selection is checked or written.
type RootSyncOptions struct {
	Root string
	// Harness names the harness owner explicitly. Empty uses the owner
	// recorded in an existing generated file.
	Harness string
	// Create writes a missing file; without it only an existing generated
	// file is refreshed.
	Create bool
	// Check reports without writing and without failing on a conflict.
	Check  bool
	DryRun bool
}

type rootSelectionDocument struct {
	Taba struct {
		Generated string `toml:"generated"`
		Harness   string `toml:"harness"`
		Ref       string `toml:"ref"`
		Commit    string `toml:"commit"`
		Pin       string `toml:"pin"`
	} `toml:"taba"`
}

type rootSelectionFile struct {
	Meta  rootSelectionDocument `toml:"_"`
	Tools map[string]any        `toml:"tools"`
}

// readRootSelection reports the recorded source of a generated root file, or
// its state when there is none. A file without the marker is the user's.
func readRootSelection(root string) (*RootSelectionSource, string, error) {
	dir := filepath.Join(root, filepath.Dir(RootSelectionFile))
	if info, err := os.Lstat(dir); os.IsNotExist(err) {
		return nil, RootSelectionMissing, nil
	} else if err != nil {
		return nil, "", err
	} else if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return nil, RootSelectionConflict, nil
	}
	path := filepath.Join(root, RootSelectionFile)
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return nil, RootSelectionMissing, nil
	}
	if err != nil {
		return nil, "", err
	}
	if !info.Mode().IsRegular() {
		return nil, RootSelectionConflict, nil
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, "", err
	}
	var doc rootSelectionFile
	if _, err := toml.Decode(string(data), &doc); err != nil || doc.Meta.Taba.Generated != rootSelectionMarker {
		return nil, RootSelectionConflict, nil
	}
	m := doc.Meta.Taba
	recorded := &RootSelectionSource{Harness: m.Harness, Ref: m.Ref, Commit: m.Commit, Pin: m.Pin}
	if version, ok := doc.Tools[cliMiseTool].(string); ok {
		recorded.Version = version
	}
	return recorded, RootSelectionStale, nil
}

func validRootHarness(harness string) error {
	if !validRepoName.MatchString(harness) {
		return fmt.Errorf("invalid harness owner name %q", harness)
	}
	return nil
}

// rootSourceProbe is where the declared default ref is looked up: the owner's
// remote default branch, else origin/main. A ref recorded in the generated
// file is provenance only and never chooses what is read.
func rootSourceProbe(owner string) string {
	if _, err := projectSnapshotGit(owner, "rev-parse", "--verify", "refs/remotes/origin/HEAD^{commit}"); err == nil {
		return "origin/HEAD"
	}
	return "origin/main"
}

// declaredHarnessRef reads the registry at commit and returns the default ref
// the harness declares for itself. An owner whose registry does not declare
// it is not a project harness.
func declaredHarnessRef(p *ProjectContext, harness, origin string) (string, error) {
	data, _, err := p.snapshotFile(".harness-repos.yml", ".harness-repos.yml")
	if err != nil {
		return "", err
	}
	if data == nil {
		return "", fmt.Errorf("harness owner %s has no .harness-repos.yml at %s", harness, p.Source.Ref)
	}
	registry, err := ParseRegistry(data)
	if err != nil {
		return "", err
	}
	for _, repo := range registry.Repos {
		if repo.Answers(harness) || origin != "" && repo.Remote == origin {
			ref := repositoryBaseFacts(repo, repoBaseStore{}, false).EffectiveRef
			if !rootRefPattern.MatchString(ref) || strings.Contains(ref, "..") {
				return "", fmt.Errorf("invalid declared harness ref %q", ref)
			}
			return ref, nil
		}
	}
	return "", fmt.Errorf("the registry in %s does not declare that harness; it is not this project's harness", harness)
}

// resolveRootSource derives the project source from the harness's shared
// owner alone: the default ref its own registry declares and the pin at that
// commit. No collection checkout, uncommitted pin or recorded metadata other
// than the owner name decides it, and nothing is fetched.
func resolveRootSource(root, harness string) (RootSelectionSource, error) {
	source := RootSelectionSource{Harness: harness}
	if err := validRootHarness(harness); err != nil {
		return source, err
	}
	source.Owner = filepath.Join(".bare", harness+".git")
	owner := filepath.Join(root, source.Owner)
	if info, err := os.Lstat(owner); err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return source, fmt.Errorf("harness owner %s is not a directory in this project", source.Owner)
	}
	resolvedRoot, err := canonicalPath(filepath.Join(root, ".bare"))
	if err != nil {
		return source, err
	}
	if resolved, err := canonicalPath(owner); err != nil || filepath.Dir(resolved) != resolvedRoot {
		return source, fmt.Errorf("harness owner %s escapes the project", source.Owner)
	}
	if bare, err := projectSnapshotGit(owner, "rev-parse", "--is-bare-repository"); err != nil || bare != "true" {
		return source, fmt.Errorf("harness owner %s is not an available bare repository", source.Owner)
	}
	origin, _ := projectSnapshotGit(owner, "config", "--get", "remote.origin.url")
	resolve := func(ref string) (*ProjectContext, error) {
		sha, err := projectSnapshotGit(owner, "rev-parse", "--verify", ref+"^{commit}")
		if err != nil || len(sha) < 40 {
			return nil, fmt.Errorf("harness ref %s is unavailable in %s; fetch the owner", ref, source.Owner)
		}
		return &ProjectContext{Source: ProjectSource{Owner: owner, Ref: sha}}, nil
	}
	probe := rootSourceProbe(owner)
	p, err := resolve(probe)
	if err != nil {
		return source, err
	}
	ref, err := declaredHarnessRef(p, harness, origin)
	if err != nil {
		return source, err
	}
	if ref != probe {
		if p, err = resolve(ref); err != nil {
			return source, err
		}
		// The declared ref must declare itself, so the source is stable.
		if again, err := declaredHarnessRef(p, harness, origin); err != nil {
			return source, err
		} else if again != ref {
			return source, fmt.Errorf("harness default ref is inconsistent: %s declares %s", ref, again)
		}
	}
	source.Ref, source.Commit = ref, p.Source.Ref
	data, name, err := p.snapshotFile(".wtc-cli-version", ".taba-version")
	if err != nil {
		return source, err
	}
	if data == nil {
		return source, fmt.Errorf("the harness pins no CLI release at %s", ref)
	}
	version := strings.TrimSpace(string(data))
	if !cliVersionPattern.MatchString(version) {
		return source, fmt.Errorf("invalid CLI version in %s at %s: %q", name, ref, version)
	}
	source.Pin, source.Version = name, version
	return source, nil
}

func renderRootSelection(source RootSelectionSource) []byte {
	var b bytes.Buffer
	b.WriteString(rootSelectionHeader)
	b.WriteString("[_.taba]\n")
	fmt.Fprintf(&b, "generated = %q\n", rootSelectionMarker)
	fmt.Fprintf(&b, "harness = %q\n", source.Harness)
	fmt.Fprintf(&b, "ref = %q\n", source.Ref)
	fmt.Fprintf(&b, "commit = %q\n", source.Commit)
	fmt.Fprintf(&b, "pin = %q\n", source.Pin)
	b.WriteString("\n[tools]\n")
	fmt.Fprintf(&b, "%q = %q\n", cliMiseTool, source.Version)
	return b.Bytes()
}

// writeRootSelection replaces the generated file atomically; an interrupted
// write leaves the previous file or none, never a partial one.
func writeRootSelection(root string, data []byte) error {
	dir := filepath.Join(root, filepath.Dir(RootSelectionFile))
	if err := os.Mkdir(dir, 0755); err != nil && !os.IsExist(err) {
		return err
	}
	if info, err := os.Lstat(dir); err != nil {
		return err
	} else if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("refusing non-directory %s", dir)
	}
	tmp, err := os.CreateTemp(dir, ".config.toml.tmp-")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0644); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), filepath.Join(root, RootSelectionFile))
}

// trustRootSelection lets mise read the generated file, as collection
// configuration is trusted when it is generated. Without mise it does nothing.
func trustRootSelection(root string) error {
	mise, err := exec.LookPath("mise")
	if err != nil {
		return nil
	}
	cmd := exec.Command(mise, "trust", filepath.Join(root, RootSelectionFile))
	cmd.Dir = root
	if output, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("mise trust failed: %w: %s", err, strings.TrimSpace(string(output)))
	}
	return nil
}

// rootSelectionOverrides lists user configuration at the root that also
// selects the CLI. mise prefers these files over the generated one.
func rootSelectionOverrides(root string) []string {
	var found []string
	for _, name := range []string{"mise.toml", ".mise.toml", "mise.local.toml", ".mise.local.toml"} {
		var doc struct {
			Tools map[string]any `toml:"tools"`
		}
		data, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			continue
		}
		if _, err := toml.Decode(string(data), &doc); err != nil {
			continue
		}
		for _, tool := range []string{cliMiseTool, legacyCLIMiseTool} {
			if _, ok := doc.Tools[tool]; ok {
				found = append(found, name)
				break
			}
		}
	}
	if data, err := os.ReadFile(filepath.Join(root, ".tool-versions")); err == nil {
		for _, line := range strings.Split(string(data), "\n") {
			fields := strings.Fields(line)
			if len(fields) > 0 && (fields[0] == cliMiseTool || fields[0] == legacyCLIMiseTool) {
				found = append(found, ".tool-versions")
				break
			}
		}
	}
	sort.Strings(found)
	return found
}

// SyncRootSelection checks, creates or refreshes the root selection.
func SyncRootSelection(opt RootSyncOptions) (RootSelectionReport, error) {
	report := RootSelectionReport{Root: opt.Root, File: RootSelectionFile, DryRun: opt.DryRun || opt.Check}
	if _, err := exec.LookPath("mise"); err != nil {
		report.MiseMissing = true
	}
	report.Overrides = rootSelectionOverrides(opt.Root)
	recorded, state, err := readRootSelection(opt.Root)
	if err != nil {
		return report, err
	}
	report.Recorded, report.State = recorded, state
	harness := opt.Harness
	if harness == "" && recorded != nil {
		harness = recorded.Harness
	}
	if harness == "" {
		report.SourceError = branding.Text("no project source is recorded; run `{{command}} env root` in a collection of this project")
	} else {
		source, err := resolveRootSource(opt.Root, harness)
		if err != nil {
			report.SourceError = err.Error()
		} else {
			report.Source = &source
			report.Content = string(renderRootSelection(source))
			if state == RootSelectionStale {
				if existing, err := os.ReadFile(filepath.Join(opt.Root, RootSelectionFile)); err == nil && string(existing) == report.Content {
					report.State = RootSelectionCurrent
				}
			}
		}
	}
	if opt.Check {
		return report, nil
	}
	switch {
	case report.State == RootSelectionConflict:
		return report, fmt.Errorf("%s at the project root is not generated by taba; it was left unchanged. Move it aside to generate the root selection, or select the CLI there yourself", RootSelectionFile)
	case report.Source == nil:
		return report, errors.New(report.SourceError)
	case report.State == RootSelectionCurrent:
		return report, nil
	case report.State == RootSelectionMissing && !opt.Create:
		return report, nil
	}
	report.Changed = true
	if opt.DryRun {
		return report, nil
	}
	if err := writeRootSelection(opt.Root, []byte(report.Content)); err != nil {
		return report, err
	}
	report.State = RootSelectionCurrent
	return report, trustRootSelection(opt.Root)
}

// RootSelectionHarness names this collection's harness owner. The project
// source itself is read from that owner, never from this checkout.
func (c *Context) RootSelectionHarness() (string, error) {
	if c.AdHoc {
		return "", fmt.Errorf("an ad-hoc collection has no project root selection")
	}
	name, err := c.HarnessRepoName()
	if err != nil {
		return "", err
	}
	bare, err := c.bareFor(name)
	if err != nil {
		return "", err
	}
	if !sameCanonicalPath(filepath.Dir(bare), filepath.Join(c.Workspace, ".bare")) {
		return "", fmt.Errorf("the harness owner is not in this project's .bare directory")
	}
	return strings.TrimSuffix(filepath.Base(bare), ".git"), nil
}

// CollectionSelection reports the CLI selection this collection generates.
func (c *Context) CollectionSelection(source *RootSelectionSource) *CollectionSelection {
	selection := &CollectionSelection{Collection: filepath.Base(c.Collection)}
	if c.Harness != "" {
		if path, err := pinInput(c.Harness); err == nil {
			if data, err := os.ReadFile(path); err == nil {
				selection.Version = strings.TrimSpace(string(data))
			}
		}
		if sha, err := gitOutput("-C", c.Harness, "rev-parse", "HEAD"); err == nil {
			selection.HarnessCommit = sha
		}
	}
	selection.Differs = source != nil && selection.Version != source.Version
	return selection
}

// refreshRootSelection keeps an existing generated root file current when a
// collection's environment is generated. It never creates or replaces a file
// it does not own, and keeps the recorded source: a collection on another
// harness revision cannot redirect it.
func (c *Context) refreshRootSelection() {
	if c.AdHoc || c.Workspace == "" {
		return
	}
	if recorded, _, err := readRootSelection(c.Workspace); err != nil || recorded == nil {
		return
	}
	_, _ = SyncRootSelection(RootSyncOptions{Root: c.Workspace})
}

// FindProjectRoot returns the nearest enclosing directory with a generated
// root selection, which records the project's harness source.
func FindProjectRoot(start string) (string, bool) {
	dir, err := canonicalPath(start)
	if err != nil {
		return "", false
	}
	for {
		if recorded, _, err := readRootSelection(dir); err == nil && recorded != nil {
			return dir, true
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", false
		}
		dir = parent
	}
}

// plannedCollectionName is the folder name NewCollection derives from opt.
func plannedCollectionName(opt NewOptions) (string, error) {
	var name string
	switch {
	case opt.PR != "":
		parts := strings.Split(opt.PR, "#")
		if len(parts) != 2 || !prNumber.MatchString(parts[1]) {
			return "", fmt.Errorf("--pr expects <repo>#<number>")
		}
		name = parts[0] + "-pr" + parts[1]
	case opt.Issue != "":
		name = opt.Issue + "-" + opt.Slug
	case opt.Tracker != "":
		name = strings.ToLower(opt.Tracker) + "-" + opt.Slug
	default:
		name = opt.Slug
	}
	if !collectionNamePattern.MatchString(name) {
		return "", fmt.Errorf("invalid collection name %q", name)
	}
	return name, nil
}

// NewCollectionAtRoot creates a collection from a project root. The new
// collection's harness is checked out first at the recorded project source,
// and that checkout is the creating configuration: no other collection, and
// no development build, is consulted.
func NewCollectionAtRoot(root string, opt NewOptions) (NewResult, *Context, error) {
	result := NewResult{}
	recorded, state, err := readRootSelection(root)
	if err != nil {
		return result, nil, err
	}
	if recorded == nil {
		return result, nil, fmt.Errorf("no generated root selection at %s (%s)", root, state)
	}
	// Validate the recorded owner before any fetch, checkout or hook: it must
	// be a harness owner in this project whose registry declares itself.
	if _, err := resolveRootSource(root, recorded.Harness); err != nil {
		return result, nil, fmt.Errorf("root selection source is not usable: %w", err)
	}
	name, err := plannedCollectionName(opt)
	if err != nil {
		return result, nil, err
	}
	if opt.Branch != "" {
		if _, err := gitOutput("check-ref-format", "--branch", opt.Branch); err != nil {
			return result, nil, fmt.Errorf("invalid explicit branch: %w", err)
		}
	}
	target := filepath.Join(root, name)
	if _, err := os.Lstat(target); err == nil {
		return result, nil, fmt.Errorf("collection already exists: %s", target)
	} else if !os.IsNotExist(err) {
		return result, nil, err
	}
	owner := filepath.Join(root, ".bare", recorded.Harness+".git")
	if _, err := gitOutput("--git-dir="+owner, "fetch", "--prune", "origin"); err != nil {
		return result, nil, err
	}
	source, err := resolveRootSource(root, recorded.Harness)
	if err != nil {
		return result, nil, err
	}
	if err := os.Mkdir(target, 0755); err != nil {
		return result, nil, err
	}
	harness := filepath.Join(target, "harness")
	args := rootHarnessWorktreeArgs(owner, harness, opt.Branch, source.Commit)
	createdBranch := len(args) > 3 && args[3] == "-b"
	cleanup := func() {
		_, _ = gitOutput("--git-dir="+owner, "worktree", "remove", "--force", harness)
		if createdBranch {
			_, _ = gitOutput("--git-dir="+owner, "branch", "-D", opt.Branch)
		}
		_ = os.Remove(target)
	}
	if _, err := gitOutput(args...); err != nil {
		_ = os.Remove(target)
		return result, nil, err
	}
	trustWorktreeMise(harness)
	creating, err := openCollection(target, true)
	if err != nil {
		cleanup()
		return result, nil, err
	}
	creating.harnessProvisioned = true
	result, err = creating.NewCollection(opt)
	if err != nil && onlyHarness(target) {
		cleanup()
	}
	return result, creating, err
}

// onlyHarness reports whether a failed root creation left nothing but the
// harness checkout it made, which is then safe to remove.
func onlyHarness(collection string) bool {
	entries, err := os.ReadDir(collection)
	return err == nil && len(entries) == 1 && entries[0].Name() == "harness"
}

// rootHarnessWorktreeArgs checks the harness out as AddWorktree would for a
// collection invocation with the same options, based on the project source.
func rootHarnessWorktreeArgs(owner, path, branch, commit string) []string {
	args := []string{"--git-dir=" + owner, "worktree", "add"}
	switch {
	case branch == "":
		return append(args, "--detach", path, commit)
	case gitRefExists(owner, "refs/heads/"+branch):
		return append(args, path, branch)
	case gitRefExists(owner, "refs/remotes/origin/"+branch):
		return append(args, "-b", branch, path, "origin/"+branch)
	default:
		return append(args, "-b", branch, path, commit)
	}
}

func gitRefExists(owner, ref string) bool {
	_, err := gitOutput("--git-dir="+owner, "rev-parse", "--verify", "--quiet", ref)
	return err == nil
}
